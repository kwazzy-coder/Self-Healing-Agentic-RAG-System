"""
analysis/update_readme.py — Paste generated result tables into README.md.

    python -m analysis.update_readme results/retrieval_n500_s42 \
        results/ragbench-covidqa_detector_n200_s42 results/hotpotqa_qa_n100_s42

Everything between the RESULTS markers in README.md is replaced with the
report.md of each directory (in the order given), so the README only ever
shows numbers that were actually produced by the evaluation scripts.
"""
from __future__ import annotations

import argparse
import os
import re
from datetime import date
from typing import List

START, END = "<!-- RESULTS:START -->", "<!-- RESULTS:END -->"


def build_section(result_dirs: List[str]) -> str:
    parts = []
    for d in result_dirs:
        path = os.path.join(d, "report.md")
        if not os.path.exists(path):
            raise FileNotFoundError(f"{path} not found — run the evaluation first")
        with open(path, encoding="utf-8") as fh:
            text = fh.read().strip()
        text = re.sub(r"^## ", "### ", text, flags=re.M)
        parts.append(text)
    stamp = f"_Generated by `analysis/update_readme.py` on {date.today().isoformat()}._"
    return "\n\n".join([stamp, *parts])


def update(readme: str, section: str) -> str:
    if START not in readme or END not in readme:
        raise ValueError("README.md has no RESULTS markers")
    head, rest = readme.split(START, 1)
    _, tail = rest.split(END, 1)
    return f"{head}{START}\n{section}\n{END}{tail}"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("result_dirs", nargs="+")
    ap.add_argument("--readme", default="README.md")
    args = ap.parse_args()
    with open(args.readme, encoding="utf-8") as fh:
        readme = fh.read()
    new = update(readme, build_section(args.result_dirs))
    with open(args.readme, "w", encoding="utf-8") as fh:
        fh.write(new)
    print(f"Updated {args.readme} with {len(args.result_dirs)} result tables.")


if __name__ == "__main__":
    main()
